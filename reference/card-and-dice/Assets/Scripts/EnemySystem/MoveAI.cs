using System;
using UnityEngine;

/// <summary>
/// 敌人移动行为预设类型（决定每回合「怎么走」）。
/// 设计依据：v2 文档 §0 怪物→移动预设映射、§4.2 预设语义。
/// 本期落地前五种：本能/包抄/拦截/风筝/远离；其余为预留扩展。
/// 注意：★2026-08-19 用户要求全部中文化（原英文值 Instinct/Flank/Kite...）。
/// 枚举值按 int 序列化，改名字不影响已保存数据（顺序不变）。
/// </summary>
public enum MoveAIPresetType
{
    本能,      // 本能：直线 A* 追击（史莱姆）
    包抄,      // 包抄：绕到玩家背对友军一侧相邻（哥布林）
    拦截,      // 拦截：移动到逃路前方极限射程堵路（追踪虫）
    风筝,      // 风筝：极限射程边打边退（强盗弓箭手）
    远离,      // 远离：拉距离 + 辅助（亡灵法师）
    // ---- 预留扩展（第二批，本期可不做）----
    守卫,      // 守卫：站桩守点
    自爆,      // 自爆：贴脸自爆
    炮台,      // 炮台：不动定点输出
    游击,      // 游击：打一下换位再打
    召唤者     // 召唤者：周期召唤
}

/// <summary>
/// 各移动预设的调优旋钮（按预设子集读取，全部集中定义便于平衡调整）。
/// 设计依据：v2 文档 §4.1、§12 调优旋钮。
/// </summary>
[Serializable]
public class MoveParams
{
    [Tooltip("风筝：保持的极限射程偏好（0=贴脸，1=极限射程）")]
    public int kiteDistance;

    [Tooltip("远离：与玩家保持的最小六边形距离")]
    public int keepAwayMinDist;

    [Tooltip("拦截：预测玩家逃路时考虑的友军视野半径")]
    public int interceptVision;
}